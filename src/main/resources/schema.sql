CREATE TABLE IF NOT EXISTS tables (
    no VARCHAR(10) PRIMARY KEY,
    seats INT NOT NULL,
    section VARCHAR(20) NOT NULL,
    current_seating_id BIGINT
);

CREATE TABLE IF NOT EXISTS seatings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_no VARCHAR(10) NOT NULL,
    state VARCHAR(20) NOT NULL,
    FOREIGN KEY (table_no) REFERENCES tables(no)
);

CREATE TABLE IF NOT EXISTS branches (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(60) NOT NULL
);

INSERT INTO branches (id, name)
SELECT 1, 'Baner'
WHERE NOT EXISTS (
    SELECT 1 FROM branches WHERE id = 1
);
-- The waitlist. A party's position is counted when it joins (1 + the parties waiting) and stored.
CREATE TABLE IF NOT EXISTS parties (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    party_id VARCHAR(10) NOT NULL UNIQUE,
    branch_id BIGINT NOT NULL REFERENCES branches(id),
    name VARCHAR(60) NOT NULL,
    covers INT NOT NULL,
    phone VARCHAR(16),
    state VARCHAR(10) NOT NULL,
    joined_at TIMESTAMP WITH TIME ZONE NOT NULL,
    position INT NOT NULL
);